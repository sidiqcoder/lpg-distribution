-- Access is through the session-authorized Edge Function, matching existing tables.
CREATE TABLE public.driver_login_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sopir_id INTEGER NOT NULL REFERENCES public.sopir(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX driver_login_reports_driver_time ON public.driver_login_reports(sopir_id, created_at DESC);
CREATE INDEX driver_login_reports_time ON public.driver_login_reports(created_at DESC);
ALTER TABLE public.driver_login_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.driver_login_reports FROM PUBLIC, anon, authenticated;

CREATE TABLE public.driver_monitoring (
  sopir_id INTEGER PRIMARY KEY REFERENCES public.sopir(id),
  camera_enabled BOOLEAN NOT NULL DEFAULT false,
  next_capture_at TIMESTAMPTZ,
  camera_error TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.driver_monitoring ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.driver_monitoring FROM PUBLIC, anon, authenticated;

CREATE TABLE public.fatigue_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sopir_id INTEGER NOT NULL REFERENCES public.sopir(id),
  capture_id UUID NOT NULL,
  captured_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  kind TEXT NOT NULL CHECK (kind IN ('foto', 'video')),
  duration_seconds INTEGER NOT NULL CHECK (duration_seconds BETWEEN 0 AND 10),
  foto TEXT,
  video TEXT,
  status TEXT NOT NULL DEFAULT 'MENUNGGU' CHECK (status IN ('MENUNGGU', 'FIT', 'PERLU_ISTIRAHAT')),
  review_note TEXT,
  reviewed_by TEXT,
  reviewed_at TIMESTAMPTZ,
  UNIQUE (sopir_id, capture_id),
  CHECK ((kind = 'foto' AND foto IS NOT NULL AND video IS NULL AND duration_seconds = 0)
    OR (kind = 'video' AND video IS NOT NULL AND foto IS NULL AND duration_seconds BETWEEN 5 AND 10))
);
CREATE INDEX fatigue_reports_driver_time ON public.fatigue_reports(sopir_id, captured_at DESC);
CREATE INDEX fatigue_reports_capture_time ON public.fatigue_reports(captured_at DESC);
ALTER TABLE public.fatigue_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.fatigue_reports FROM PUBLIC, anon, authenticated;
ALTER TABLE public.sopir ADD COLUMN sertifikat_submitted_at TIMESTAMPTZ;

-- Preserve existing login history where sessions are still available.
INSERT INTO public.driver_login_reports (sopir_id, created_at)
SELECT a.sopir_id, s.created_at FROM lpg_private.sessions s
JOIN lpg_private.accounts a ON a.username = s.username WHERE a.role = 'driver';
