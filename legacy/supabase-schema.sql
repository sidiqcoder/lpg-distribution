-- =====================================================================
-- supabase-schema.sql
-- Skema Database PostgreSQL untuk Supabase - Aplikasi Distribusi LPG
-- =====================================================================

-- 1. Tabel SOPIR
CREATE TABLE IF NOT EXISTS sopir (
  id INTEGER PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  nama TEXT NOT NULL,
  lisensi_expiry TEXT,
  k3_expiry TEXT,
  sertifikat_k3 TEXT,
  nomor_hp TEXT
);

-- 2. Tabel KENDARAAN
CREATE TABLE IF NOT EXISTS kendaraan (
  id INTEGER PRIMARY KEY,
  plat_nomor TEXT UNIQUE NOT NULL,
  kapasitas_ton INTEGER,
  tipe_tangki TEXT
);

-- 3. Tabel INSPEKSI PAGI
CREATE TABLE IF NOT EXISTS inspeksi_pagi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  kendaraan_id INTEGER REFERENCES kendaraan(id),
  ban_kondisi BOOLEAN,
  rem_berfungsi BOOLEAN,
  lampu_hidup BOOLEAN,
  tangki_integritas BOOLEAN,
  tidak_ada_kebocoran BOOLEAN,
  pemadam_ada BOOLEAN,
  p3k_ada BOOLEAN,
  kit_tumpah_ada BOOLEAN,
  sopir_fit BOOLEAN,
  dokumen_lengkap BOOLEAN,
  foto_kendaraan TEXT,
  foto_ban TEXT,
  foto_rem TEXT,
  foto_lampu TEXT,
  foto_bak TEXT,
  foto_kebocoran TEXT,
  foto_pemadam TEXT,
  foto_p3k TEXT,
  foto_kit TEXT,
  foto_dokumen TEXT,
  catatan TEXT,
  status_sopir TEXT DEFAULT 'PENDING',
  status_validasi TEXT DEFAULT 'MENUNGGU',
  validasi_oleh TEXT,
  validasi_waktu TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  checklist_json TEXT,
  lampiran_json TEXT,
  CONSTRAINT idx_inspeksi_unik_harian UNIQUE (sopir_id, tanggal)
);
CREATE INDEX IF NOT EXISTS idx_inspeksi_sopir_tanggal ON inspeksi_pagi(sopir_id, tanggal);

-- 4. Tabel PENGIRIMAN
CREATE TABLE IF NOT EXISTS pengiriman (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  kendaraan_id INTEGER REFERENCES kendaraan(id),
  pangkalan_nama TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  jumlah_dikirim_kg INTEGER,
  penerima_nama TEXT,
  penerima_hp TEXT,
  waktu_tiba TIME,
  waktu_selesai TIME,
  kondisi_pengiriman TEXT,
  foto_sebelum TEXT,
  foto_proses TEXT,
  foto_sesudah TEXT,
  tanda_tangan TEXT,
  catatan TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 5. Tabel RUTE HARIAN
CREATE TABLE IF NOT EXISTS rute_harian (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  kendaraan_id INTEGER REFERENCES kendaraan(id),
  urutan INTEGER,
  pangkalan_id INTEGER,
  pangkalan_nama TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  permintaan_ton INTEGER,
  estimasi_waktu_tiba TIME
);

-- 6. Tabel ROUTE HISTORY
CREATE TABLE IF NOT EXISTS route_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  kendaraan_id INTEGER REFERENCES kendaraan(id),
  rute_sequence TEXT,
  total_distance_km DOUBLE PRECISION,
  total_time_minutes INTEGER,
  total_ton INTEGER,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 7. Tabel LOKASI SOPIR (GPS Realtime)
CREATE TABLE IF NOT EXISTS lokasi_sopir (
  sopir_id INTEGER PRIMARY KEY REFERENCES sopir(id),
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  accuracy DOUBLE PRECISION,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 8. Tabel LAPORAN BAHAYA
CREATE TABLE IF NOT EXISTS laporan_bahaya (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  kendaraan_id INTEGER REFERENCES kendaraan(id),
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  jenis_bahaya TEXT,
  deskripsi TEXT,
  foto_bukti TEXT,
  status TEXT DEFAULT 'PENDING',
  admin_response TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  resolved_at TIMESTAMPTZ
);

-- 9. Tabel KPI SOPIR
CREATE TABLE IF NOT EXISTS kpi_sopir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  nilai INTEGER,
  catatan TEXT,
  input_by TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 10. Tabel PERSEDIAAN LPG
CREATE TABLE IF NOT EXISTS persediaan_lpg (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  jumlah INTEGER NOT NULL DEFAULT 1200,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 11. Tabel PERMINTAAN LPG
CREATE TABLE IF NOT EXISTS permintaan_lpg (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  sopir_id INTEGER REFERENCES sopir(id),
  kendaraan_id INTEGER REFERENCES kendaraan(id),
  jumlah_diminta INTEGER,
  status TEXT DEFAULT 'MENUNGGU',
  disetujui_oleh TEXT,
  waktu_disetujui TIMESTAMPTZ,
  catatan TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT idx_permintaan_unik_harian UNIQUE (sopir_id, tanggal)
);

